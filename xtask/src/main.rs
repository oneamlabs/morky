//! Build helper for Marky. It replaces the Node notice generator, so the repository needs no
//! JavaScript toolchain.
//!
//! Usage: `cargo run -p xtask -- notices`

use std::collections::{HashMap, HashSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::OnceLock;

use regex::Regex;

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let result = match args.first().map(String::as_str) {
        Some("notices") => write_notices(),
        _ => Err("usage: cargo run -p xtask -- notices".to_string()),
    };
    if let Err(error) = result {
        eprintln!("{error}");
        std::process::exit(1);
    }
}

struct Package {
    id: String,
    license: String,
    folder: Option<PathBuf>,
}

fn write_notices() -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().ok_or("xtask has no parent folder")?;
    let packages = crate_packages(root)?;
    let mut groups: Vec<(String, Vec<&Package>)> = Vec::new();
    let mut without_file: Vec<&Package> = Vec::new();
    for package in &packages {
        let mut texts = license_texts(package.folder.as_deref(), &package.license);
        if texts.is_empty() {
            texts.extend(template_text(package));
        }
        if texts.is_empty() {
            without_file.push(package);
            continue;
        }
        let text = texts.join("\n\n---\n\n");
        match groups.iter_mut().find(|(known, _)| *known == text) {
            Some((_, members)) => members.push(package),
            None => groups.push((text, vec![package])),
        }
    }

    let rule = "=".repeat(80);
    let mut out = format!(
        "THIRD-PARTY NOTICES\n\nMarky (MIT, see LICENSE) includes the third-party software listed below.\nSource code for every crate is available from its registry page:\nhttps://crates.io/crates/<name>/<version>.\n{} packages. Generated by `cargo run -p xtask -- notices`; do not edit by hand.\n",
        packages.len()
    );
    for (text, members) in &groups {
        out.push_str(&format!("\n{rule}\n"));
        out.push_str(&members.iter().map(|package| format!("{}: {}", package.id, package.license)).collect::<Vec<_>>().join("\n"));
        out.push_str(&format!("\n{rule}\n\n{text}\n"));
    }
    if !without_file.is_empty() {
        out.push_str(&format!("\n{rule}\nPackages that ship no license file (license as declared by the package):\n{rule}\n\n"));
        out.push_str(&without_file.iter().map(|package| format!("{}: {}", package.id, package.license)).collect::<Vec<_>>().join("\n"));
        out.push('\n');
    }

    fs::write(root.join("THIRD_PARTY_NOTICES.txt"), &out).map_err(|error| format!("could not write THIRD_PARTY_NOTICES.txt: {error}"))?;
    println!(
        "THIRD_PARTY_NOTICES.txt: {} packages, {} distinct license texts, {} without a license file, {} KB",
        packages.len(),
        groups.len(),
        without_file.len(),
        out.len() / 1024
    );
    Ok(())
}

fn crate_packages(root: &Path) -> Result<Vec<Package>, String> {
    // Cargo metadata gives every package's manifest path, which is also where its license files live
    // for registry and Git dependencies alike. `cargo tree` lists only the crates linked into Marky.
    let metadata = cargo(
        root,
        &["metadata", "--format-version", "1", "--manifest-path", "Cargo.toml"],
    )?;
    let metadata: serde_json::Value = serde_json::from_str(&metadata).map_err(|error| format!("could not parse cargo metadata: {error}"))?;
    let mut by_name: HashMap<String, (String, Option<PathBuf>)> = HashMap::new();
    for package in metadata.get("packages").and_then(serde_json::Value::as_array).into_iter().flatten() {
        let (Some(name), Some(version)) = (package["name"].as_str(), package["version"].as_str()) else { continue };
        let license = package["license"].as_str().unwrap_or_default().to_string();
        let folder = package["manifest_path"].as_str().map(Path::new).and_then(Path::parent).map(Path::to_path_buf);
        by_name.insert(format!("{name} {version}"), (license, folder));
    }

    let tree = cargo(
        root,
        &[
            "tree",
            "-p",
            "marky",
            "--manifest-path",
            "Cargo.toml",
            "--target",
            "x86_64-pc-windows-msvc",
            "-e",
            "normal,no-proc-macro",
            "--prefix",
            "none",
            "--no-dedupe",
            "--format",
            "{p}|{l}",
        ],
    )?;
    let mut seen = Vec::new();
    let mut seen_keys = HashSet::new();
    for line in tree.lines() {
        let Some((package, tree_license)) = line.trim().split_once('|') else { continue };
        let mut parts = package.split_whitespace();
        let (Some(name), Some(version)) = (parts.next(), parts.next()) else { continue };
        let Some(version) = version.strip_prefix('v') else { continue };
        if name == "marky" || name == "xtask" {
            continue;
        }
        let key = format!("{name} {version}");
        if !seen_keys.insert(key.clone()) {
            continue;
        }
        let (metadata_license, folder) = by_name.get(&key).cloned().unwrap_or_default();
        let license = if metadata_license.is_empty() { tree_license.trim().to_string() } else { metadata_license };
        let license = if license.is_empty() { "UNKNOWN".to_string() } else { license };
        seen.push(Package { id: format!("{name} {version} (crate)"), license, folder });
    }
    // The TypeScript generator sorted with `localeCompare`, which ignores `-` and `_` at the
    // primary weight (`bit_field` before `bit-set`, `float-cmp` before `float_next`).
    seen.sort_by(|a, b| sort_key(&a.id).cmp(&sort_key(&b.id)).then_with(|| a.id.cmp(&b.id)));
    Ok(seen)
}

fn sort_key(id: &str) -> String {
    id.chars().filter(|ch| *ch != '-' && *ch != '_').collect()
}

fn cargo(root: &Path, args: &[&str]) -> Result<String, String> {
    let output = Command::new("cargo")
        .args(args)
        .current_dir(root)
        .output()
        .map_err(|error| format!("could not run cargo {}: {error}", args.join(" ")))?;
    if !output.status.success() {
        return Err(format!("cargo {} failed: {}", args.join(" "), String::from_utf8_lossy(&output.stderr).trim()));
    }
    String::from_utf8(output.stdout).map_err(|error| format!("cargo {} printed invalid UTF-8: {error}", args.join(" ")))
}

/// Identical license texts are printed once with every package that uses them, so a paragraph such
/// as the MIT text does not repeat hundreds of times.
fn license_texts(folder: Option<&Path>, spdx: &str) -> Vec<String> {
    let Some(folder) = folder else { return Vec::new() };
    let Ok(entries) = fs::read_dir(folder) else { return Vec::new() };
    let mut files: Vec<String> = entries
        .flatten()
        .filter_map(|entry| entry.file_name().into_string().ok())
        .filter(|name| license_file().is_match(name))
        .collect();
    files.sort();
    let chosen = if has_word(spdx, "MIT") {
        files.iter().find(|name| name.to_lowercase().contains("mit")).map(|name| vec![name.clone()]).unwrap_or(files)
    } else {
        files
    };
    chosen
        .iter()
        .filter_map(|name| fs::read_to_string(folder.join(name)).ok())
        .map(|text| text.replace("\r\n", "\n").trim().to_string())
        .collect()
}

fn template_text(package: &Package) -> Option<String> {
    let holder = || copyright_holder(package);
    if has_word(&package.license, "MIT") {
        return Some(mit_template(&holder()));
    }
    if has_word(&package.license, "BSD-3-Clause") {
        return Some(bsd_template(&holder()));
    }
    None
}

fn copyright_holder(package: &Package) -> String {
    let manifest = package
        .folder
        .as_ref()
        .map(|folder| folder.join("Cargo.toml"))
        .filter(|path| path.is_file())
        .and_then(|path| fs::read_to_string(path).ok())
        .unwrap_or_default();
    let names: Vec<String> = authors_section()
        .captures(&manifest)
        .map(|captures| {
            author_name()
                .captures_iter(&captures[1])
                .map(|name| name[1].trim().to_string())
                .filter(|name| !name.is_empty())
                .collect()
        })
        .unwrap_or_default();
    match names.is_empty() {
        true => format!("the {} authors", package.id.split_whitespace().next().unwrap_or("")),
        false => names.join(", "),
    }
}

fn has_word(text: &str, word: &str) -> bool {
    let pattern = match word {
        "MIT" => mit_word(),
        "BSD-3-Clause" => bsd_word(),
        _ => return false,
    };
    pattern.is_match(text)
}

fn license_file() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"(?i)^(licen[cs]e|copying|notice)").expect("license file pattern is valid"))
}

fn authors_section() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"(?m)^authors\s*=\s*\[([^\]]*)\]").expect("authors pattern is valid"))
}

fn author_name() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r#""([^"<]+?)\s*(?:<[^>]*>)?""#).expect("author name pattern is valid"))
}

fn mit_word() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"\bMIT\b").expect("MIT pattern is valid"))
}

fn bsd_word() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"\bBSD-3-Clause\b").expect("BSD pattern is valid"))
}

